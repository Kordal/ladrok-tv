def ring_png(path, size, density, fill_alpha=38):
    """Circular 9-patch: 15% white fill (reads as #262626 on black) + 2dp Silver ring."""
    ss = 8
    big = Image.new("RGBA", ((size - 2) * ss, (size - 2) * ss), (0, 0, 0, 0))
    dr = ImageDraw.Draw(big)
    stroke = max(1, round(2 * density)) * ss
    dr.ellipse([0, 0, big.width - 1, big.height - 1], fill=(0xCF, 0xCF, 0xCF, 255))
    dr.ellipse([stroke, stroke, big.width - 1 - stroke, big.height - 1 - stroke],
               fill=(255, 255, 255, fill_alpha))
    inner = big.resize((size - 2, size - 2), Image.LANCZOS)
    im = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    im.paste(inner, (1, 1))
    px = im.load()
    c0, c1 = (size - 1) // 2, size // 2  # same stretch/padding geometry as the originals
    for p in {c0, c1}:
        px[p, 0] = (0, 0, 0, 255)
        px[0, p] = (0, 0, 0, 255)
    for p in range(1, size - 1):
        px[p, size - 1] = (0, 0, 0, 255)
        px[size - 1, p] = (0, 0, 0, 255)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    im.save(path)


