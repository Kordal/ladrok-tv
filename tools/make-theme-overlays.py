NS = 'xmlns:android="http://schemas.android.com/apk/res/android"'


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def overlay(name, pkg, target, priority=1, res=None, extra_bp=""):
    d = os.path.join(OUT, name)
    write(os.path.join(d, "Android.bp"), f'''// Ladrok TV black/grey theme for {target}.
runtime_resource_overlay {{
    name: "{name}",
    resource_dirs: ["res"],
    certificate: "platform",
    product_specific: true,
    sdk_version: "current",{extra_bp}
}}
''')
    write(os.path.join(d, "AndroidManifest.xml"), f'''{HDR}<manifest {NS}
    package="{pkg}">
    <application android:hasCode="false" />
    <overlay
        android:targetPackage="{target}"
        android:isStatic="true"
        android:priority="{priority}" />
</manifest>
''')
    for rel, text in (res or {}).items():
        write(os.path.join(d, "res", rel), text)
    return d


def colors(d):
    body = "".join(f'    <color name="{k}">{v}</color>\n' for k, v in d.items())
    return f"{HDR}<resources>\n{body}</resources>\n"


def strings(d):
    body = "".join(f'    <string name="{k}">{v}</string>\n' for k, v in d.items())
    return f"{HDR}<resources>\n{body}</resources>\n"


def selector(items):
    body = ""
    for color, states in items:
        st = "".join(f' android:state_{s}' if "=" in s else f' android:state_{s}="true"' for s in states)
        body += f'    <item android:color="{color}"{st} />\n'
    return f"{HDR}<selector {NS}>\n{body}</selector>\n"


def shape(fill, radius=None, stroke=None, extra=""):
    s = f'    <solid android:color="{fill}" />\n'
    if stroke:
        s += f'    <stroke android:width="{stroke[0]}" android:color="{stroke[1]}" />\n'
    if radius:
        s += f'    <corners android:radius="{radius}" />\n'
    return f'{HDR}<shape {NS}\n    android:shape="rectangle">\n{s}{extra}</shape>\n'


def switch_colors(prefix):
    """Switch rule: on = Silver thumb / Muted track, off = Muted thumb / Line track."""
    c = {}
    for focus in ("default", "focused"):
        c[f"{prefix}_thumb_on_{focus}_color"] = SILVER
        c[f"{prefix}_thumb_off_{focus}_color"] = MUTED
        c[f"{prefix}_thumb_on_{focus}_disabled_color"] = DISABLED
        c[f"{prefix}_thumb_off_{focus}_disabled_color"] = DISABLED
        c[f"{prefix}_track_on_{focus}_color"] = MUTED
        c[f"{prefix}_track_off_{focus}_color"] = LINE
        c[f"{prefix}_track_on_{focus}_disabled_color"] = LINE
        c[f"{prefix}_track_off_{focus}_disabled_color"] = LINE
        c[f"{prefix}_track_decoration_on_{focus}_color"] = MUTED
        c[f"{prefix}_track_decoration_off_{focus}_color"] = LINE
        c[f"{prefix}_track_decoration_on_{focus}_disabled_color"] = LINE
        c[f"{prefix}_track_decoration_off_{focus}_disabled_color"] = LINE
    return c


